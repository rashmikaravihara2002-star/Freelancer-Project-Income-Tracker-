import jsPDF from 'jspdf';
import 'jspdf-autotable';
import { formatCurrency, formatDate } from './formatters';

export const generateInvoicePDF = (income, user) => {
  const doc = new jsPDF();

  // Header Background Banner
  doc.setFillColor(37, 99, 235); // Brand Blue #2563eb
  doc.rect(0, 0, 210, 38, 'F');

  // Title
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('INVOICE / RECEIPT', 14, 22);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Invoice #: ${income.invoiceNumber || 'INV-001'}`, 14, 30);
  doc.text(`Date: ${formatDate(income.paymentDate || new Date())}`, 140, 22);
  doc.text(`Status: ${(income.paymentStatus || 'Paid').toUpperCase()}`, 140, 30);

  // Freelancer Info & Client Info
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('ISSUED BY (FREELANCER):', 14, 50);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(user?.name || 'Freelance Professional', 14, 57);
  doc.text(user?.title || 'Software Engineer', 14, 63);
  doc.text(user?.email || '', 14, 69);
  if (user?.phone) doc.text(user.phone, 14, 75);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('BILLED TO (CLIENT):', 120, 50);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const client = income.clientId || {};
  doc.text(client.name || 'Client', 120, 57);
  if (client.company) doc.text(client.company, 120, 63);
  doc.text(client.email || '', 120, 69);
  if (client.phone) doc.text(client.phone, 120, 75);

  // Line Items Table
  const project = income.projectId || {};
  const tableData = [
    [
      project.projectName || 'Professional Services / Milestone',
      income.paymentMethod || 'Bank Transfer',
      income.notes || 'Project milestone deliverables and development fees',
      formatCurrency(income.amount),
    ],
  ];

  doc.autoTable({
    startY: 88,
    head: [['Item & Project Description', 'Payment Method', 'Notes / Scope', 'Amount']],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [37, 99, 235],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
    },
    styles: {
      fontSize: 9.5,
      cellPadding: 5,
    },
    columnStyles: {
      3: { halign: 'right', fontStyle: 'bold' },
    },
  });

  // Total Box
  const finalY = doc.lastAutoTable.finalY + 15;

  doc.setFillColor(248, 250, 252);
  doc.roundedRect(120, finalY, 76, 28, 3, 3, 'F');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text('Total Amount:', 125, finalY + 10);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(37, 99, 235);
  doc.text(formatCurrency(income.amount), 125, finalY + 22);

  // Footer notes
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'italic');
  doc.text('Thank you for your business. Generated by Freelancer Project & Income Tracker.', 14, 275);

  doc.save(`${income.invoiceNumber || 'invoice'}.pdf`);
};

export const generateIncomeReportPDF = (incomes, summary, user) => {
  const doc = new jsPDF('landscape');

  // Header Banner
  doc.setFillColor(15, 23, 42); // Slate 900
  doc.rect(0, 0, 297, 32, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('FREELANCER FINANCIAL & INCOME REPORT', 14, 18);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(`Generated: ${formatDate(new Date(), 'PPP')} | User: ${user?.name || 'Freelancer'} (${user?.email || ''})`, 14, 26);

  // Summary Metrics Banner
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`Total Paid Income: ${formatCurrency(summary.totalIncome)}`, 14, 42);
  doc.text(`Pending Receivables: ${formatCurrency(summary.pendingIncome)}`, 100, 42);
  doc.text(`Total Transactions: ${incomes.length}`, 190, 42);

  // Table Data
  const tableData = incomes.map((i) => [
    i.invoiceNumber || 'INV-N/A',
    formatDate(i.paymentDate),
    i.projectId?.projectName || 'General Project',
    i.clientId?.name || 'Client',
    i.paymentMethod || 'Bank Transfer',
    i.paymentStatus || 'Paid',
    formatCurrency(i.amount),
  ]);

  doc.autoTable({
    startY: 48,
    head: [['Invoice #', 'Date', 'Project', 'Client', 'Method', 'Status', 'Amount']],
    body: tableData,
    theme: 'striped',
    headStyles: {
      fillColor: [37, 99, 235],
      textColor: [255, 255, 255],
    },
    styles: {
      fontSize: 8.5,
      cellPadding: 3.5,
    },
    columnStyles: {
      6: { halign: 'right', fontStyle: 'bold' },
    },
  });

  doc.save(`income_report_${formatDate(new Date(), 'yyyy-MM-dd')}.pdf`);
};
